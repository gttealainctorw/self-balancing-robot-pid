#!/usr/bin/env python3
"""Packs web/ into firmware/balance_robot/web_assets.h.

The robot serves its web app from flash, so the sources in web/ are turned
into gzip blobs with content-hashed URLs (cached for a year by the browser):

  web/index.html              -> /, /control and /statistics (same document)
  web/img/*.webp              -> /a/<hash>/<name>.webp    (already compressed)
  web/app.css                 -> /a/<hash>/app.css
  web/js/*.js (sorted, joined)-> /a/<hash>/app.js
  web/model/robot.bin         -> /a/<hash>/robot.bin
  web/fonts/*.woff2           -> /a/<hash>/<name>.woff2   (already compressed)

Placeholders such as {{app.css}} in index.html and app.css are replaced by
the hashed URLs.

Usage: python tools/build_web.py          (standard library only)
The dev server imports build() from this file, so it always serves the
current sources.
"""
import gzip
import hashlib
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, 'web')
HEADER = os.path.join(ROOT, 'firmware', 'balance_robot', 'web_assets.h')


def read(*parts, binary=False):
    with open(os.path.join(WEB, *parts), 'rb') as f:
        data = f.read()
    return data if binary else data.decode('utf-8').replace('\r\n', '\n')


def gz(data):
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode='wb', compresslevel=9, mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def bundle_js():
    names = sorted(n for n in os.listdir(os.path.join(WEB, 'js')) if n.endswith('.js'))
    parts = ['/* %s */\n%s' % (n, read('js', n)) for n in names]
    return "(function(){'use strict';\n" + '\n'.join(parts) + '\n})();\n'


def build():
    """Returns a list of assets: dict(path, type, data, gzip, immutable, raw_len)."""
    assets = []
    urls = {}

    def hashed(name, ctype, data, compress):
        url = '/a/%s/%s' % (hashlib.sha1(data).hexdigest()[:8], name)
        urls[name] = url
        body = gz(data) if compress else data
        assets.append(dict(path=url, type=ctype, data=body, gzip=compress, immutable=True, raw_len=len(data)))

    def fill(text):
        for name, url in urls.items():
            text = text.replace('{{%s}}' % name, url)
        if '{{' in text:
            raise SystemExit('unresolved placeholder near: ' + text[text.index('{{'):][:40])
        return text

    for name in sorted(os.listdir(os.path.join(WEB, 'fonts'))):
        if name.endswith('.woff2'):
            hashed(name, 'font/woff2', read('fonts', name, binary=True), False)
    for name in sorted(os.listdir(os.path.join(WEB, 'img'))):
        if name.endswith('.webp'):
            hashed(name, 'image/webp', read('img', name, binary=True), False)
    hashed('robot.bin', 'application/octet-stream', read('model', 'robot.bin', binary=True), True)
    hashed('app.css', 'text/css', fill(read('app.css')).encode(), True)
    hashed('app.js', 'application/javascript', bundle_js().encode(), True)
    html = fill(read('index.html')).encode()
    shell = dict(path='/control', type='text/html', data=gz(html), gzip=True, immutable=False, raw_len=len(html))
    return [shell] + assets


def write_header(assets):
    out = ['// Generated by tools/build_web.py from the files in web/. Do not edit by hand.',
           '// The web app (HTML, CSS, JS, 3D model, fonts) as gzip blobs served from flash.',
           '#pragma once', '#include <Arduino.h>', '',
           'struct WebAsset {', '  const char* path;', '  const char* type;', '  const uint8_t* data;',
           '  uint32_t len;', '  bool gzip;', '  bool immutable;', '};', '']
    for i, a in enumerate(assets):
        out.append('// %s  (%d bytes, %d before compression)' % (a['path'], len(a['data']), a['raw_len']))
        out.append('static const uint8_t WEB_ASSET_%d[] PROGMEM = {' % i)
        d = a['data']
        for k in range(0, len(d), 40):
            out.append(','.join(str(b) for b in d[k:k + 40]) + ',')
        out.append('};')
        out.append('')
    out.append('// Entry 0 is the HTML document, used for /, /control and /statistics.')
    out.append('static const WebAsset WEB_ASSETS[] = {')
    for i, a in enumerate(assets):
        out.append('  {"%s", "%s", WEB_ASSET_%d, %d, %s, %s},' % (
            a['path'], a['type'], i, len(a['data']), 'true' if a['gzip'] else 'false',
            'true' if a['immutable'] else 'false'))
    out.append('};')
    out.append('static const uint8_t WEB_ASSET_COUNT = %d;' % len(assets))
    out.append('')
    with open(HEADER, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))


def main():
    assets = build()
    write_header(assets)
    total = 0
    for a in assets:
        total += len(a['data'])
        print('%-34s %7d bytes%s' % (a['path'], len(a['data']),
                                     '  (gzip of %d)' % a['raw_len'] if a['gzip'] else ''))
    print('total sent to a new device: %d bytes' % total)
    print('wrote', os.path.relpath(HEADER, ROOT))


if __name__ == '__main__':
    main()
